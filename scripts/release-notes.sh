#!/bin/bash
#
# Текст выпуска для GitHub — по образцу SmartBase (Scripts/github-release/release-notes.sh). Печатает готовый markdown.
#
#   scripts/release-notes.sh 0.1.5                               # посмотреть, что получится
#   scripts/release-notes.sh 0.1.5 artifacts/release > notes.md  # так вызывает release.yml: заодно сверяет, что каждый
#                                                                # названный файл есть в папке выпуска
#
# Состав: «Что нового» из секции версии в CHANGELOG.md → какой файл качать и что с ним сделать → что нажать при первом
# запуске → как ставить новую версию → как сверить загрузку. Ничего лишнего: страница выпуска — место, где человек
# скачивает программу, а не читает отчет о работе. Списка коммитов нет намеренно (решение пользователя 2026-11-10: из
# коммитов в v0.1.0-beta.1 попали 424 строки и чужой участник): что изменилось — сказано человеческим языком, полная
# история — на расстоянии одной ссылки со страницы выпуска. Нет секции — нет и текста: выпуск останавливается.
#
# Сети и gh не требует: собирается целиком из файлов репозитория.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
HISTORY="${RELEASE_CHANGELOG:-$ROOT/CHANGELOG.md}"
VERSION="${1:-}"
FOLDER="${2:-}"

[ -n "$VERSION" ] || { echo "Использование: release-notes.sh <версия> [папка выпуска]" >&2; exit 1; }
[ -f "$HISTORY" ] || { echo "Нет файла $HISTORY" >&2; exit 1; }

# ── Что нового: секция «## [версия]» до следующего «## [» ─────────────────────
BODY="$(awk -v v="${VERSION//./\\.}" '
  $0 ~ "^## \\[" v "\\]" { found = 1; next }
  found && /^## \[/      { exit }
  # Сноски-ссылки в конце файла («[0.1.5]: https://…») — разметка истории, а не описание версии.
  found && /^\[[^]]*\]:/ { next }
  found                  { print }
' "$HISTORY")"

# Пустые строки в начале секции — прочь; в конце их уже съела подстановка $(...).
BODY="$(printf '%s\n' "$BODY" | sed -e '/./,$!d')"

# Перенос строки внутри абзаца или пункта GitHub на странице выпуска показывает разрывом, как в комментариях. В
# CHANGELOG.md строки переносятся по ширине, поэтому здесь они склеиваются: продолжение пункта (отступ) и строка текста
# сразу после строки текста — к предыдущей через пробел. Заголовки, пункты, таблицы и пустые строки — каждая своя.
BODY="$(printf '%s\n' "$BODY" | awk '
  function own(s) { return s == "" || s ~ /^(#|- |\* |[0-9]+\. |\||```|>)/ }
  {
    text = $0
    sub(/^[ \t]+/, "", text)
    if (have && prev != "" && prev !~ /^(#|\||```)/ && !own(text)) {
      prev = prev " " text
      next
    }
    if (have) print prev
    prev = $0; have = 1
  }
  END { if (have) print prev }
')"

if [ -z "$BODY" ]; then
  echo "В CHANGELOG.md нет непустой секции «## [$VERSION]» — опишите версию до выпуска" >&2
  exit 1
fi

# «@слово» GitHub считает упоминанием учетной записи и ставит ее в «Contributors» выпуска — так в v0.1.0-beta.1 попал
# чужой пользователь param («@param:ApplicationContext» из темы коммита). Такое слово пишется кодом; почта (буква перед
# «@») и слово уже в обратных кавычках не трогаются.
BODY="$(printf '%s\n' "$BODY" | sed -E 's/(^|[^[:alnum:]_`])(@[[:alnum:]]([[:alnum:]_.:/-]*[[:alnum:]_])?)/\1`\2`/g')"

PACKAGE="${VERSION//-/\~}"
MSI="PrivateGateway-$VERSION-win-x64.msi"
DMG="PrivateGateway-$VERSION-osx-arm64.dmg"
DEB="private-gateway_${PACKAGE}_amd64.deb"
RPM="private-gateway-${PACKAGE}-1.x86_64.rpm"
APK="PrivateGateway-$VERSION-android.apk"

# С папкой выпуска — каждый файл из таблицы должен в ней быть: иначе страница советует скачать то, чего нет.
if [ -n "$FOLDER" ]; then
  missing=""
  for file in "$MSI" "$DMG" "$DEB" "$RPM" "$APK"; do
    [ -f "$FOLDER/$file" ] || missing="$missing $file"
  done
  if [ -n "$missing" ]; then
    echo "В $FOLDER нет файлов, которые называет текст выпуска:$missing" >&2
    exit 1
  fi
fi

if [[ "$VERSION" == *-* ]]; then
  echo "Бета-выпуск: приходит тем, у кого в «О программе» выбран канал «Бета»."
  echo
fi
echo "## Что нового"
echo
printf '%s\n' "$BODY"
echo
cat <<EOF
## Установка

| ОС | Файл | Что делать |
|---|---|---|
| Windows 10 и 11 | \`$MSI\` | скачать и запустить |
| macOS, Apple Silicon | \`$DMG\` | открыть образ, перетащить Private Gateway в «Программы» |
| Linux: Debian, Ubuntu | \`$DEB\` | \`sudo apt install ./$DEB\` |
| Linux: Fedora, openSUSE | \`$RPM\` | \`sudo dnf install ./$RPM\` |
| Android 9 и новее | \`$APK\` | открыть на телефоне и разрешить установку из этого источника |

Скачивается **один файл** для своей системы, .NET ставить не нужно. Службу защиты ставит установщик, на macOS — сама программа при первом запуске (спросит пароль администратора). Архивы \`.zip\` и \`.tar.gz\` — та же программа без установщика. Приложение для iPhone и iPad — в разработке: появится после подписи Apple.

### Первый запуск

Программа пока не подписана сертификатом разработчика, поэтому система спросит подтверждение — один раз.

**Windows.** Если появится синее окно «Система Windows защитила ваш компьютер»:

1. Нажмите **«Подробнее»**.
2. Внизу окна появится кнопка **«Выполнить в любом случае»** — нажмите ее.

**macOS.** Инструкция нарисована прямо в окне образа, коротко:

1. Перетащите Private Gateway в «Программы» и откройте ее оттуда.
2. Появится окно про проверку программы — нажмите **«Готово»**.
3. Откройте **Системные настройки ▸ Конфиденциальность и безопасность** и прокрутите вниз до раздела **«Безопасность»**.
4. Рядом с названием программы нажмите **«Все равно открыть»** и подтвердите.

**Linux.** Ничего дополнительно делать не нужно.

**Android.** При первом подключении телефон спросит разрешение на VPN — нажмите **«ОК»**.

## Обновление

Новая версия ставится поверх прежней тем же способом: скачайте файл новой версии и запустите его. Серверы, подписки и настройки сохраняются.

## Сверка загрузки

Рядом со скачанным файлом положите \`SHA256SUMS\` и выполните \`sha256sum -c SHA256SUMS --ignore-missing\` (Linux, Git Bash на Windows) или \`shasum -a 256 -c SHA256SUMS --ignore-missing\` (macOS); для Android — свой файл \`$APK.sha256\`. Состав программы — файлы \`*.cdx.json\` (SBOM), лицензии открытых компонентов — \`THIRD-PARTY-NOTICES.txt\` в папке программы.
EOF
